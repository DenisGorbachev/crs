impl ReviewSolution {
    pub fn meets(self, requirements: &ReviewRequirements) -> bool {
        let properties = self.properties();
        properties.effort <= requirements.maximum_effort && (!requirements.keyboard_only || properties.keyboard_selection) && (!requirements.local_only || !properties.requires_hosted_review) && (!requirements.require_exact_patch || properties.capture.preserves_exact_patch()) && (!requirements.require_file_and_side || properties.capture.preserves_file_and_side()) && (!requirements.require_partial_hunks || properties.selection.supports_partial_hunks()) && (!requirements.require_multiline_ranges || properties.selection.supports_multiline_ranges()) && (!requirements.require_character_selection || properties.selection == Characters)
    }

    pub fn decide(candidates: impl IntoIterator<Item = Self>, requirements: &ReviewRequirements, mut keystrokes_for_review: impl FnMut(Self) -> ReviewKeystrokes) -> Option<Self> {
        candidates
            .into_iter()
            .filter(|solution| solution.meets(requirements))
            .map(|solution| (keystrokes_for_review(solution), solution.properties().effort, solution))
            .min_by_key(|(keystrokes, effort, _)| (*keystrokes, *effort))
            .map(|(_, _, solution)| solution)
    }
}
