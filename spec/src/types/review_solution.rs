macro_rules! review_solutions {
    ($($variant:ident { $($field:ident: $value:expr),+ $(,)? }),+ $(,)?) => {
        #[derive(ValueEnum, EnumIter, Serialize, Deserialize, Eq, PartialEq, Hash, Clone, Copy, Debug)]
        #[value(rename_all = "kebab-case")]
        pub enum ReviewSolution {
            $($variant),+
        }

        impl ReviewSolution {
            pub fn properties(self) -> ReviewSolutionProperties {
                use ReviewSolution::*;
                match self {
                    $($variant => ReviewSolutionProperties { $($field: $value),+ }),+
                }
            }
        }
    };
}

